# Characters the titles actually use that the font lacks, mapped to the
# nearest ones it has. Anything else is dropped after NFKD folding, so an
# accent loses its mark rather than turning into a box.
_FOLD = {"—": "-", "–": "-", "−": "-", "·": "*", "•": "*",
         "‘": "'", "’": "'", "“": '"', "”": '"', "×": "X"}


def font_text(s):
    s = "".join(_FOLD.get(c, c) for c in s)
    s = unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode()
    return "".join(c for c in s.upper() if c in FONT)


class Canvas:
    """An RGB pixel buffer with just enough drawing for a preview card."""

    def __init__(self, w, h, bg):
        self.w, self.h = w, h
        self.buf = bytearray(bytes(bg) * (w * h))

    def rect(self, x0, y0, x1, y1, rgb):
        x0, x1 = max(0, int(x0)), min(self.w, int(x1))
        y0, y1 = max(0, int(y0)), min(self.h, int(y1))
        if x0 >= x1:
            return
        row = bytes(rgb) * (x1 - x0)
        for y in range(y0, y1):
            i = (y * self.w + x0) * 3
            self.buf[i:i + len(row)] = row

    def dot(self, cx, cy, r, rgb):
        for dy in range(-r, r + 1):
            half = int(math.sqrt(r * r - dy * dy) + 0.5)
            self.rect(cx - half, cy + dy, cx + half + 1, cy + dy + 1, rgb)

    def line(self, pts, rgb, r, dash=0):
        """A polyline r pixels thick; dash > 0 draws dash-pixel dashes."""
        walked = 0.0
        for (x0, y0), (x1, y1) in zip(pts, pts[1:]):
            steps = max(1, int(max(abs(x1 - x0), abs(y1 - y0))))
            seg = math.hypot(x1 - x0, y1 - y0) / steps
            for k in range(steps + 1):
                if not dash or int(walked / dash) % 2 == 0:
                    self.dot(int(x0 + (x1 - x0) * k / steps), int(y0 + (y1 - y0) * k / steps), r, rgb)
                walked += seg if k < steps else 0

    def text(self, x, y, s, scale, rgb):
        for c in s:
            for gy, row in enumerate(FONT[c]):
                for gx, bit in enumerate(row):
                    if bit == "#":
                        self.rect(x + gx * scale, y + gy * scale,
                                  x + (gx + 1) * scale, y + (gy + 1) * scale, rgb)
            x += 6 * scale


def text_width(s, scale):
    return max(0, len(s) * 6 * scale - scale)


def wrap(s, scale, width):
    lines, cur = [], ""
    for word in s.split():
        trial = f"{cur} {word}".strip()
        if cur and text_width(trial, scale) > width:
            lines.append(cur)
            cur = word
        else:
            cur = trial
    return lines + ([cur] if cur else [])


def _hex(c):
    return tuple(int(c[i:i + 2], 16) for i in (1, 3, 5))


def _mix(a, b, t):
    return tuple(round(x + (y - x) * t) for x, y in zip(a, b))


