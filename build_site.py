def _curves(demo, box):
    """[(kind, points)] in pixels for the preview's plot, kind in ref/main/fill.

    Rough shapes of each topic's own animation - the same ones app.js draws on
    the home page cards - so a preview looks like the page it opens.
    """
    x0, y0, x1, y1 = box

    def px(fn, n=240, u0=0.0, u1=1.0):
        out = []
        for i in range(n + 1):
            u = u0 + (u1 - u0) * i / n
            a, b = fn(u)
            out.append((x0 + a * (x1 - x0), y1 - max(0.0, min(1.0, b)) * (y1 - y0)))
        return out

    if demo == "taylor":
        def p5(u):
            x = u * 12 - 6
            return x - x ** 3 / 6 + x ** 5 / 120
        # Stop the polynomial where it leaves the frame - running it flat
        # along the edge would hide the point of the topic, that it diverges.
        inside = [i / 600 for i in range(601) if abs(p5(i / 600)) <= 1.5]
        return [("ref", px(lambda u: (u, 0.5 + 0.32 * math.sin(u * 12 - 6)))),
                ("main", px(lambda u: (u, 0.5 + 0.32 * p5(u)), 240, inside[0], inside[-1]))]
    if demo == "projectile":
        return [("dash", px(lambda u: (u, 3.4 * u * (1 - u)))),
                # Drag: shorter, lower, and it comes down steeper than it went up.
                ("main", px(lambda u: (u * 0.78, 1.8 * u * (1 - u * u))))]
    if demo == "boltzmann":
        def mb(u):
            x = u * 3.2
            return u, 2.2 * x * x * math.exp(-x * x / 1.1)
        return [("fill", px(mb, 120, 0.52, 1.0)), ("main", px(mb))]
    if demo == "orbitals":
        cy, h = (y0 + y1) / 2, (y1 - y0) / 2
        s = [(x0 + 1.1 * h + h * math.cos(a), cy + h * math.sin(a))
             for a in (2 * math.pi * i / 180 for i in range(181))]
        p = []
        for i in range(361):
            a = 2 * math.pi * i / 360
            r = 2.2 * h * abs(math.cos(a)) ** 1.2
            p.append((x0 + 5.2 * h + r * math.cos(a), cy + 0.42 * r * math.sin(a)))
        return [("main", s), ("main", p)]
    # No port yet (or the home page): a damped wave, the collection's motif.
    return [("ref", px(lambda u: (u, 0.5 + 0.4 * math.sin(u * 14)))),
            ("main", px(lambda u: (u, 0.5 + 0.42 * math.exp(-2.2 * u) * math.sin(u * 14))))]


def og_image(title, band_text, demo, colour, w=1200, h=630):
    """A 1200x630 preview: subject band, title, and the topic's curve."""
    pad = 72
    c = Canvas(w, h, BG)
    c.rect(0, 0, w, 96, colour)
    c.text(pad, 34, font_text(band_text), 4, (255, 255, 255))

    # The largest scale at which the title fits in three lines and still
    # leaves the plot most of the lower half; a long title gets smaller type
    # rather than a squashed curve.
    words = font_text(title)
    for scale in (10, 9, 8, 7, 6, 5):
        lines = wrap(words, scale, w - 2 * pad)
        if len(lines) * 10 * scale <= 250 and all(text_width(ln, scale) <= w - 2 * pad
                                                  for ln in lines):
            break
    y = 140
    for ln in lines[:3]:
        c.text(pad, y, ln, scale, INK)
        y += 10 * scale

    box = (pad, max(y + 30, 380), w - pad, 548)
    tint = _mix(BG, colour, 0.28)
    for kind, pts in _curves(demo, box):
        if kind == "fill":
            for (xa, ya), (xb, _) in zip(pts, pts[1:]):
                c.rect(xa, ya, xb + 1, box[3], tint)
        elif kind == "main":
            c.line(pts, colour, 5)
        else:
            c.line(pts, REF, 3, dash=18 if kind == "dash" else 0)
    c.rect(pad, box[3] + 4, w - pad, box[3] + 7, _mix(BG, INK, 0.15))   # axis

    c.rect(pad, 580, pad + 18, 598, colour)
    c.text(pad + 30, 580, font_text(SITE_NAME), 3, INK_SOFT)
    return png_bytes(w, h, c.buf)


# ----------------------------------------------------------------- writing
def write_text(path, text):
    """Write text with LF endings, only if it changed. Returns True if written.

    On a Windows checkout with core.autocrlf the file on disk has CRLF endings
    while the new text has LF; that is not a change, and rewriting it would
    only churn mtimes.
    """
    data = text.encode("utf-8")
    if path.exists() and path.read_bytes().replace(b"\r\n", b"\n") == data:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    return True


def write_png(path, data):
    if path.exists() and png_pixels(path.read_bytes()) == png_pixels(data):
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    return True


def prune(docs, ids):
    """Remove pages and images for topics that no longer exist.

    Only directories whose page carries the GENERATED marker, so nothing
    written by hand under docs/t/ is ever deleted.
    """
    removed = []
    tdir = docs / "t"
    if tdir.is_dir():
        for d in sorted(tdir.iterdir()):
            page = d / "index.html"
            if d.is_dir() and d.name not in ids and page.exists() \
                    and MARKER in page.read_text(encoding="utf-8", errors="replace"):
                shutil.rmtree(d)
                removed.append(d)
    odir = docs / "og"
    if odir.is_dir():
        for f in sorted(odir.glob("*.png")):
            if f.stem not in ids and f.stem != "home":
                f.unlink()
                removed.append(f)
    return removed


def load_topics(root):
    path = root / "topics.json"
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        raise BuildError(f"no topics.json at {path}")
    except json.JSONDecodeError as e:
        raise BuildError(f"topics.json is not valid JSON: {e}")


def build(root=ROOT, site=None, quiet=False):
    """Validate topics.json under root and regenerate everything in docs/.

    Returns the list of paths that were written or removed.
    """
    root = Path(root)
    site = site_url(site)
    topics = load_topics(root)
    validate(topics, root)

    docs = root / "docs"
    changed = []

    embedded = []
    for t in topics:
        t = dict(t)
        t["source"] = (root / t["folder"] / t["script"]).read_text(encoding="utf-8")
        t["script_url"] = f"{t['folder']}/{t['script']}"
        t["notebook_url"] = f"{REPO}/blob/main/{t['folder']}/{t['notebook']}"
        t["colab_url"] = (
            f"https://colab.research.google.com/github/iyu210-tech/"
            f"Capstone_Repository/blob/main/{t['folder']}/{t['notebook']}"
        )
        embedded.append(t)
    payload = json.dumps(embedded, indent=2, ensure_ascii=False)
    js = f"// {MARKER} by hand.\nwindow.TOPICS = {payload};\n"
    if write_text(docs / "topics.js", js):
        changed.append(docs / "topics.js")

    index = docs / "index.html"
    if not index.exists():
        raise BuildError(f"no template at {index}")
    template = home_page(index.read_text(encoding="utf-8").replace("\r\n", "\n"), site)
    if write_text(index, template):
        changed.append(index)

    for t in topics:
        page = docs / "t" / t["id"] / "index.html"
        if write_text(page, topic_page(template, t, site)):
            changed.append(page)
        colour = SUBJECT_COLOURS.get(t["subject"], ACCENT)
        img = og_image(t["title"], f"{t['subject']} · {t['syllabus']}", t.get("demo"), colour)
        if write_png(docs / "og" / f"{t['id']}.png", img):
            changed.append(docs / "og" / f"{t['id']}.png")

    home_img = og_image("Hard IB topics you can run", "IB Higher Level * Maths * Physics * Chemistry",
                        None, ACCENT)
    if write_png(docs / "og" / "home.png", home_img):
        changed.append(docs / "og" / "home.png")

    if write_text(docs / "sitemap.xml", sitemap(topics, site)):
        changed.append(docs / "sitemap.xml")
    if write_text(docs / "robots.txt", robots(site)):
        changed.append(docs / "robots.txt")

    changed += prune(docs, {t["id"] for t in topics})

    if not quiet:
        print(f"built {len(topics)} topics for {site}")
        for p in changed:
            print(f"  wrote {p.relative_to(root).as_posix()}" if p.exists()
                  else f"  removed {p.relative_to(root).as_posix()}")
        if not changed:
            print("  everything already up to date")
    return changed


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--root", type=Path, default=ROOT,
                    help="repository to build (default: the one this file is in)")
    args = ap.parse_args(argv)
    try:
        build(args.root)
    except BuildError as e:
        # A plain message and a non-zero exit, not a traceback: this is what a
        # Vercel or Render build log shows, and it should say what to fix.
        print(f"build_site.py: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
