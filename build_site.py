"""Generate the website's derived files from topics.json plus the real sources.

The website never stores its own copy of the code - it is embedded here at
build time, straight from the .py files. Edit a script, re-run this, and the
site is back in sync.

What it writes, all under docs/:

  topics.js          every topic, with its Python source embedded
  t/<id>/index.html  a real page per topic, so a link can be crawled and shared
  og/<id>.png        the link-preview image for each topic, plus og/home.png
  sitemap.xml        every page, for search engines
  robots.txt         points crawlers at the sitemap
  index.html         only its canonical and preview URLs, which follow SITE_URL

Everything here is stdlib only. Vercel and Render both run this with no pip
install, and it has to stay that way - the topic scripts' matplotlib/scipy
dependencies are for running the topics, not for building the site.

Run:  python build_site.py
      SITE_URL=https://example.vercel.app/ python build_site.py
      python build_site.py --root path/to/another/checkout
"""

